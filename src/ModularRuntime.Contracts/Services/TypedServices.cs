namespace ModularRuntime.Contracts;

/// <summary>Definition supplied when registering a typed service.</summary>
/// <param name="ServiceId">Unique service identifier (a <see cref="RuntimeName"/>), shared with JSON and binary services.</param>
/// <param name="Name">Display name, 1-200 characters.</param>
/// <param name="Version">Service version (major.minor[.build]); consumers may require a minimum.</param>
public sealed record TypedServiceDefinition(
    string ServiceId,
    string Name,
    Version Version)
{
    public IReadOnlyDictionary<string, string>? Metadata { get; init; }
}

/// <summary>
/// Consumer handle to a typed service, bound to one registration.
/// </summary>
/// <typeparam name="TContract">The contract interface.</typeparam>
/// <remarks>
/// <see cref="Service"/> is a runtime-generated proxy, never the provider's object. It can be
/// kept after the provider stops without keeping the provider alive; calls then fail with
/// <see cref="TypedServiceException"/> (<c>service_removed</c>).
/// </remarks>
public interface ITypedServiceClient<out TContract>
    where TContract : class
{
    string ServiceId { get; }

    Guid RegistrationId { get; }

    bool IsAvailable { get; }

    /// <summary>The proxy implementing <typeparamref name="TContract"/>.</summary>
    TContract Service { get; }

    /// <summary>Current descriptor of the bound registration, or <see langword="null"/> after removal.</summary>
    PluginServiceDescriptor? GetDescriptor();
}

/// <summary>
/// A callback registered by its owner and handed to other plugins as a shared delegate.
/// </summary>
/// <typeparam name="TDelegate">The delegate type (a framework or contract delegate type).</typeparam>
/// <remarks>
/// <see cref="Callback"/> is a runtime-generated delegate that forwards to the registered target
/// through the owner's scope: calls are admitted and drained like typed-service calls, arguments
/// and results are checked, exceptions are translated. The runtime drops the target when the
/// registration is released (the owner stops or disposes it); a holder that invokes the delegate
/// afterwards gets <see cref="TypedServiceException"/> (<c>callback_released</c>) and keeps nothing
/// of the owner alive.
/// </remarks>
public interface ICallbackRegistration<out TDelegate> : IPluginResource
    where TDelegate : Delegate
{
    /// <summary>The shared delegate to hand to other plugins. Never the registered target itself.</summary>
    TDelegate Callback { get; }
}

/// <summary>
/// Typed services: a provider registers an object implementing a C# interface; consumers call it
/// through a proxy generated by the runtime. Provider and consumer share the interface through a
/// <b>shared contract assembly</b> declared in both manifests (<c>sharedContracts</c>), which the
/// runtime loads once per version line so both see the same <see cref="Type"/>.
/// </summary>
/// <remarks>
/// <para>
/// Calls are direct in-process calls: no serialization, no copy of arguments or results. The
/// runtime adds admission (a stopping provider rejects new calls and cancels in-flight ones),
/// per-call cancellation linking for <see cref="CancellationToken"/> parameters, exception
/// translation, and reentrancy tracking. Arguments and results must be <b>shared values</b>: their
/// types, and the types of everything they reference, come from the contract assembly, from
/// <c>ModularRuntime.Contracts</c>, or from the framework. An object whose type lives in a
/// plugin's private assembly keeps that plugin's load context alive for as long as the other side
/// holds it. By default the runtime verifies every value crossing a typed boundary (its type, the
/// targets of delegates, the elements of collections, the fields of objects whose type does not
/// settle the question) and rejects offenders with <c>value_not_shared</c>, or values it cannot
/// verify within its limits with <c>value_not_verifiable</c> (see the host's
/// <c>RuntimeLimits.TypedValueCheck</c>). Callbacks are passed through
/// <see cref="RegisterCallback{TDelegate}"/>, never as raw delegates over plugin code.
/// </para>
/// <para>
/// Exceptions thrown by the provider propagate to the caller unchanged when their type is
/// shared (contract assembly, framework, <c>ModularRuntime.Contracts</c>); any other exception is
/// replaced by <see cref="TypedServiceException"/> (<c>handler_failed</c>) carrying a text-only
/// diagnostic. Methods returning <see cref="Task"/> or <see cref="ValueTask"/> report failures
/// through the returned task.
/// </para>
/// <para>
/// Typed services are not a sandbox: the provider's code runs in the caller's thread with the
/// process's permissions, and a blocking provider blocks its caller.
/// </para>
/// </remarks>
public interface ITypedServiceRegistry
{
    /// <summary>
    /// Registers <paramref name="instance"/> as the provider of <paramref name="definition"/>.
    /// The registration is owned by the calling scope; when it is released the runtime drops its
    /// reference to the instance and every proxy bound to it becomes inactive.
    /// </summary>
    /// <typeparam name="TContract">A public interface without static abstract members.</typeparam>
    /// <exception cref="ArgumentException">The definition is invalid.</exception>
    /// <exception cref="PluginRuntimeException">
    /// <c>duplicate_service</c>, <c>typed_service_invalid_contract</c>, <c>scope_closed</c>, or <c>engine_disposed</c>.
    /// </exception>
    IServiceRegistration Register<TContract>(TypedServiceDefinition definition, TContract instance)
        where TContract : class;

    /// <summary>
    /// Returns a proxy bound to the current registration of <paramref name="serviceId"/>, or
    /// <see langword="null"/> when the service is not registered, is not a typed service, or its
    /// version is incompatible.
    /// </summary>
    /// <exception cref="PluginRuntimeException">
    /// <c>typed_service_contract_mismatch</c>: the service exists but its contract is a different
    /// <see cref="Type"/> than <typeparamref name="TContract"/> (usually because one side did not
    /// declare the contract assembly in <c>sharedContracts</c> and loaded a private copy).
    /// </exception>
    TContract? Resolve<TContract>(string serviceId, Version? minimumVersion = null)
        where TContract : class;

    /// <summary>Like <see cref="Resolve{TContract}"/>, with availability and descriptor access.</summary>
    ITypedServiceClient<TContract>? GetClient<TContract>(string serviceId, Version? minimumVersion = null)
        where TContract : class;

    /// <summary>
    /// Registers <paramref name="target"/> as a callback owned by the calling scope and returns a
    /// shared delegate of the same type that forwards to it. Hand <see cref="ICallbackRegistration{TDelegate}.Callback"/>
    /// to other plugins (as a typed-service argument, a stream item, or a property): it holds
    /// nothing of this plugin, is invalidated when the registration is released, and admits calls
    /// through this owner's scope like a typed service.
    /// </summary>
    /// <typeparam name="TDelegate">A delegate type from the framework or a shared contract assembly, whose signature uses shared types.</typeparam>
    /// <param name="name">Display name of the registration, 1-200 characters.</param>
    /// <exception cref="ArgumentException">The name or delegate type is invalid.</exception>
    /// <exception cref="PluginRuntimeException"><c>typed_service_invalid_contract</c>, <c>scope_closed</c>, or <c>engine_disposed</c>.</exception>
    ICallbackRegistration<TDelegate> RegisterCallback<TDelegate>(string name, TDelegate target)
        where TDelegate : Delegate;
}

/// <summary>
/// Thrown by typed-service proxies and callback delegates for runtime conditions: the provider
/// stopped (<c>service_unavailable</c>, <c>service_removed</c>; <c>callback_unavailable</c>,
/// <c>callback_released</c> for callbacks), the caller stopped (<c>scope_closed</c>), the runtime
/// was disposed (<c>engine_disposed</c>), a value crossing the boundary is not shared
/// (<c>value_not_shared</c>) or could not be verified (<c>value_not_verifiable</c>), or the callee
/// threw an exception of a non-shared type (<c>handler_failed</c>, with
/// <see cref="PluginRuntimeException.Diagnostic"/>).
/// </summary>
public sealed class TypedServiceException : PluginRuntimeException
{
    public TypedServiceException(string errorCode, string message, PluginDiagnostic? diagnostic = null)
        : base(errorCode, message, diagnostic)
    {
    }

    public TypedServiceException(string errorCode, string message, string serviceId, PluginDiagnostic? diagnostic = null)
        : base(errorCode, message, diagnostic)
    {
        ServiceId = serviceId;
    }

    /// <summary>The service the failing call targeted, when known (<see langword="null"/> for callbacks).</summary>
    public string? ServiceId { get; }
}
